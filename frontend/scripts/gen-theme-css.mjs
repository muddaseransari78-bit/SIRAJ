// Builds src/theme/themes.css and public/theme-init.js from src/theme/themes.js.
// Runs automatically before `npm run dev`, `build` and `test`. You can also run it by hand: npm run theme:css
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { THEMES, DEFAULT_THEME, THEME_KEY, COLOR_KEYS, hexToTriplet } from "../src/theme/themes.js";

export function buildCss() {
  const blocks = THEMES.map((t) => {
    const vars = COLOR_KEYS.map((k) => `  --noor-${k}: ${hexToTriplet(t.c[k])};`).join("\n");
    const sel = t.id === DEFAULT_THEME ? `:root,\nhtml[data-theme="${t.id}"]` : `html[data-theme="${t.id}"]`;
    return `${sel} {\n${vars}\n  color-scheme: ${t.mode};\n}`;
  });
  return `/* AUTO-GENERATED from src/theme/themes.js by scripts/gen-theme-css.mjs - do not edit by hand. */\n${blocks.join("\n\n")}\n`;
}

export function buildInit() {
  const map = THEMES.map((t) => `"${t.id}":["${t.mode}","${t.c.bg.toLowerCase()}"]`).join(",");
  return `/* AUTO-GENERATED by scripts/gen-theme-css.mjs - runs before first paint so the saved theme shows with no flash. */
(function () {
  try {
    var map = {${map}};
    var id = localStorage.getItem("${THEME_KEY}");
    if (!map[id]) id = "${DEFAULT_THEME}";
    var root = document.documentElement;
    root.setAttribute("data-theme", id);
    root.setAttribute("data-mode", map[id][0]);
    root.style.colorScheme = map[id][0];
    root.style.backgroundColor = map[id][1];
    var meta = document.querySelector('meta[name="theme-color"]');
    if (meta) meta.setAttribute("content", map[id][1]);
  } catch (e) { /* storage blocked: the default theme stays */ }
})();
`;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  writeFileSync(new URL("../src/theme/themes.css", import.meta.url), buildCss());
  writeFileSync(new URL("../public/theme-init.js", import.meta.url), buildInit());
  console.log(`Theme files written (${THEMES.length} themes).`);
}
